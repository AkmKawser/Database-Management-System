"""
Universal Skill Generator for Database Management System (and Science of Coding)
Generates Type 1 (Fixed Resources) and Type 2 (Dynamic Resources) skills
conforming exactly to the verified repository architecture.
"""

import os
import sys
import argparse
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[4]

def create_type1_fixed_resource_skill(skill_name, resource_type, source_path_rel, description=""):
    """
    Type 1: Fixed Resource Skill (Book / Udemy Course / PDF Manual)
    """
    skill_dir = BASE_DIR / ".agent" / "skills" / "SkillsOnFixedResources" / skill_name
    output_dir = BASE_DIR / "Skills_Output" / f"{skill_name}_output"
    
    # 1. Directories
    (skill_dir / "SkillArchitecture").mkdir(parents=True, exist_ok=True)
    (skill_dir / "references").mkdir(parents=True, exist_ok=True)
    (skill_dir / "scripts").mkdir(parents=True, exist_ok=True)
    (output_dir / "outline").mkdir(parents=True, exist_ok=True)
    (BASE_DIR / "Skills_Output" / "query").mkdir(parents=True, exist_ok=True)

    print(f"📁 Created directory structure for Type 1 Skill: {skill_name}")

    # 2. SKILL.md
    skill_md_content = f"""---
name: {skill_name}
description: {description or f"Expert reference skill for {skill_name} ({resource_type}) with surgical search, deep outline navigation, and topic query manual generation."}
---

# `{skill_name}`: Reference & Architecture Skill

The **`{skill_name}`** skill provides authoritative, reference-grounded explanations, architectural analyses, and query outputs based on the resources located in [`{source_path_rel}`](../../../../{source_path_rel}).

---

## 🎯 Skill Purpose & Trigger Rules

Activate this skill when:
1. The user mentions `@{skill_name}` or asks for concepts covered in this resource.
2. The user requests deep-dive manuals to be saved into `Skills_Output/{skill_name}_output/query/`.
3. The user wants to search or explore the complete curriculum outline in `Skills_Output/{skill_name}_output/outline/`.

---

## 📂 Source Knowledge Structure

- **Source Asset**: [`{source_path_rel}`](../../../../{source_path_rel})
- **Exhaustive Curriculum / Book Outline**: [`Skills_Output/{skill_name}_output/outline/{skill_name}_Complete_Course_Outline.md`](../../../../Skills_Output/{skill_name}_output/outline/{skill_name}_Complete_Course_Outline.md)
- **Table of Contents Routing**: [`references/table_of_contents.md`](references/table_of_contents.md)
- **Search & Query CLI**: [`scripts/query_{skill_name.lower()}.py`](scripts/query_{skill_name.lower()}.py)

---

## 📝 Output Generation Protocol (`Skills_Output/{skill_name}_output/query/`)

All topic outputs generated by this skill must follow the standardized manual structure:
1. **Title & Resource Context**: Section, Chapter, or Lecture references.
2. **The Intuition First**: Plain-English explanation and core dilemma.
3. **Internal Mechanics & Engine Pipeline**: Mermaid flowcharts/diagrams showing execution under the hood.
4. **Execution vs Syntax Comparison**: Logical vs physical operations.
5. **Practical Examples & Verification**: Runnable SQL/Code blocks and tests.
6. **Performance Pitfalls & Invariant Rules**: Edge cases, anti-patterns, and Big-O / latency cost.
"""
    with open(skill_dir / "SKILL.md", "w", encoding="utf-8") as f:
        f.write(skill_md_content)

    # 3. SkillArchitecture/ARCHITECTURE.md
    arch_md_content = f"""# Architecture & Operational Mechanics: `{skill_name}` Skill

## 1. System Overview & Purpose

The **`{skill_name}`** skill is a portable, self-contained, agent-agnostic knowledge and retrieval module encapsulating:
* **Resource Type**: {resource_type}
* **Source Path**: `{source_path_rel}`
* **Architecture Standard**: SkillsOnFixedResources (Type 1)

---

## 2. Directory Layout

```
.agent/skills/SkillsOnFixedResources/{skill_name}/
├── SkillArchitecture/
│   ├── ARCHITECTURE.md                  <-- Technical specifications (this file)
│   └── {skill_name}_Architecture_README.md  <-- High-level overview & agent execution rules
├── SKILL.md                             <-- Universal agent entrypoint & query decision rules
├── references/
│   ├── table_of_contents.md             <-- Fast human & agent topic index
│   └── toc.json                         <-- Machine-readable outline tree
└── scripts/
    └── query_{skill_name.lower()}.py        <-- Precision CLI search & extraction
```

---

## 3. High-Level Architecture Diagram

```mermaid
flowchart TD
    User([User Prompt / Topic Request]) --> Agent[Agentic AI Engine]
    
    subgraph KnowledgeSources["Tri-Source Knowledge Ingestion"]
        direction TB
        SourceData["Source Material ({source_path_rel})"]
        Router["Zero-Token Fast Router<br/>(table_of_contents.md / toc.json)"]
        CLISearch["Precision CLI Search<br/>(python query_{skill_name.lower()}.py)"]
        
        Router --> CLISearch
        SourceData --> CLISearch
        
        LLM["Pre-trained Reasoning & Memory"]
        Web["Targeted Web Search & Docs"]
    end
    
    Agent --> KnowledgeSources
    
    subgraph SynthesisLayer["Analysis & Synthesis Layer"]
        direction TB
        Step1["Analyze Theoretical Foundations & Invariants"]
        Step2["Dissect Engine Operations / Relational Algebra"]
        Step3["Synthesize Visual Architecture Diagram (Mermaid)"]
        Step1 --> Step2 --> Step3
    end
    
    KnowledgeSources --> SynthesisLayer
    SynthesisLayer --> Output["Standardized Query Output<br/>(Skills_Output/{skill_name}_output/query/<NNN>_<topic>.md)"]
```
"""
    with open(skill_dir / "SkillArchitecture" / "ARCHITECTURE.md", "w", encoding="utf-8") as f:
        f.write(arch_md_content)

    # 4. SkillArchitecture/<skill>_Architecture_README.md
    arch_readme_content = f"""# Skill Architecture & Usage Instructions: `{skill_name}`

This document defines the technical architecture, execution pipeline, and usage guidelines for the **`{skill_name}`** skill.

---

## 🏛️ System Architecture

The `{skill_name}` skill connects any agentic AI system to domain knowledge without suffering from context exhaustion, token window degradation, or hallucinations.

## 📖 Operational Instructions for Agents

1. **Surgical Search First**: Never answer from memory alone. Run `scripts/query_{skill_name.lower()}.py "<topic>"` to retrieve verified citations.
2. **Deep Outline Verification**: Check `Skills_Output/{skill_name}_output/outline/` for exact section and topic matches.
3. **Standardized Manual Output**: Output all requested topics into `Skills_Output/{skill_name}_output/query/<NNN>_<topic>.md`.
"""
    with open(skill_dir / "SkillArchitecture" / f"{skill_name}_Architecture_README.md", "w", encoding="utf-8") as f:
        f.write(arch_readme_content)

    # 5. Output README
    output_readme_content = f"""# `{skill_name}_output` Query Hub & Manual Archive

This directory stores in-depth manuals and curriculum outlines for **`{skill_name}`**.

---

## ⚡ Navigation: Curriculum Outline & Query Manuals

- 🗺️ **[Complete Curriculum / Topic Outline](outline/{skill_name}_Complete_Course_Outline.md)**: Exhaustive hierarchical index of all sections, subtopics, and resources.
- 📁 **[Generated Deep-Dive Query Manuals](query/)**: Topic manuals covering theoretical foundations and engine internals.

---

## 📑 Generated Query Manuals Index

| Query ID | Topic / Manual Title | Source Section | Companion Reference | Status |
| :---: | :--- | :--- | :--- | :---: |
| `001` | *Staging Initial Set...* | — | — | ⏳ Pending |
"""
    with open(output_dir / f"{skill_name}_Output_README.md", "w", encoding="utf-8") as f:
        f.write(output_readme_content)

    # 6. Starter query script
    cli_script_content = f"""\"\"\"
Precision Query CLI for {skill_name}
\"\"\"
import sys
import argparse
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[4]
SOURCE_DIR = BASE_DIR / "{source_path_rel.replace('\\', '/')}"

def search_resource(keyword):
    print(f"🔍 Searching {skill_name} for keyword: '{{keyword}}'...")
    matches = []
    for file in SOURCE_DIR.rglob("*.*"):
        if file.suffix.lower() in [".md", ".txt", ".sql", ".py", ".json"]:
            try:
                with open(file, "r", encoding="utf-8", errors="ignore") as f:
                    content = f.read()
                    if keyword.lower() in content.lower():
                        matches.append(file)
            except:
                pass
    print(f"Found {{len(matches)}} matching files:")
    for m in matches[:10]:
        print(f"  📄 {{m.relative_to(BASE_DIR)}}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Query {skill_name} resources")
    parser.add_argument("keyword", help="Keyword to search")
    args = parser.parse_args()
    search_resource(args.keyword)
"""
    with open(skill_dir / "scripts" / f"query_{skill_name.lower()}.py", "w", encoding="utf-8") as f:
        f.write(cli_script_content)

    print(f"✅ Successfully initialized Type 1 Fixed Resource Skill: {skill_name}")


def create_type2_dynamic_resource_skill(skill_name, target_category_doc, description=""):
    """
    Type 2: Dynamic Resource Skill (Problem Ingestion, HITL Categorization, Solutions)
    """
    skill_dir = BASE_DIR / ".agent" / "skills" / "SkillsOnDynamicResources" / skill_name
    output_dir = BASE_DIR / "Skills_Output" / f"{skill_name}_output"
    
    # 1. Directories
    (skill_dir / "SkillArchitecture").mkdir(parents=True, exist_ok=True)
    (skill_dir / "scripts").mkdir(parents=True, exist_ok=True)
    (output_dir / "Problem Files" / "Source of Problem" / "put the file here").mkdir(parents=True, exist_ok=True)
    (output_dir / "Solution Files").mkdir(parents=True, exist_ok=True)

    print(f"📁 Created directory structure for Type 2 Skill: {skill_name}")

    # 2. SKILL.md
    skill_md_content = f"""---
name: {skill_name}
description: {description or f"Dedicated dynamic skill for managing problem intake, HITL categorization, and standardized solution generation for {skill_name}."}
---

# Problem Ingestion & Solution Engineering Skill (`{skill_name}`)

The **`{skill_name}`** skill controls the lifecycle of dynamic problem intake into [`Skills_Output/{skill_name}_output/Problem Files/question bank.md`](../../../../Skills_Output/{skill_name}_output/Problem%20Files/question%20bank.md) and the synthesis of template-grounded solutions into [`Skills_Output/{skill_name}_output/Solution Files/`](../../../../Skills_Output/{skill_name}_output/Solution%20Files/).

---

## 🎯 Primary Triggers & Capabilities

Activate this skill when:
1. The user mentions `@{skill_name}` to check, format, or process problems.
2. The user requests to process a specific file path or document from `put the file here/`.
3. The user requests to process a specific problem number or staging text.
4. The user asks to solve a problem from `question bank.md`.

---

## 🤝 Human-in-the-Loop (HITL) Category Protocol

Whenever processing a problem, the agent **MUST NOT** guess the category or subcategory arbitrarily.
1. Read the dynamic categories from `{target_category_doc}`.
2. Interactively prompt the user (HITL) to confirm the **Primary Category** and **Subcategory**.
3. Format the problem into `question bank.md` adhering to `problem formatting.md`.
4. Generate dialect-separated solution files under `Solution Files/<Primary Category>/<Subcategory>/`.

---

## 🚨 CRITICAL RULE: Non-Destructive Ingestion

- **Zero Data Loss Guarantee**: Never delete any source file or notes until the entry is 100% verified inside `question bank.md`.
"""
    with open(skill_dir / "SKILL.md", "w", encoding="utf-8") as f:
        f.write(skill_md_content)

    # 3. SkillArchitecture/ARCHITECTURE.md
    arch_md_content = f"""# Architecture & Operational Mechanics: `{skill_name}` Skill

## 1. System Overview & Purpose

The **`{skill_name}`** skill manages dynamic problem intake, interactive human-in-the-loop classification, non-destructive archiving, and multi-dialect solution generation.

---

## 2. Directory Layout

```
.agent/skills/SkillsOnDynamicResources/{skill_name}/
├── SkillArchitecture/
│   ├── ARCHITECTURE.md                  <-- Technical specifications (this file)
│   └── {skill_name}_Architecture_README.md  <-- High-level overview & agent execution rules
├── SKILL.md                             <-- Universal agent entrypoint & decision rules
└── scripts/
    └── ingest_manager.py                <-- Autonomous queue scanner & HITL parser
```
"""
    with open(skill_dir / "SkillArchitecture" / "ARCHITECTURE.md", "w", encoding="utf-8") as f:
        f.write(arch_md_content)

    # 4. Output files formatting & question bank
    (output_dir / "Problem Files" / "problem formatting.md").write_text("# Problem Formatting Specification\n\nAdhere to standard schema.\n", encoding="utf-8")
    (output_dir / "Problem Files" / "question bank.md").write_text("# Master Question Bank\n\n| ID | Problem Title | Primary Category | Subcategory | Difficulty | Solution Link |\n| :---: | :--- | :--- | :--- | :---: | :---: |\n", encoding="utf-8")
    (output_dir / f"{skill_name}_Output_README.md").write_text(f"# `{skill_name}_output` Hub\n\nArchive of problem files and solution files.\n", encoding="utf-8")

    print(f"✅ Successfully initialized Type 2 Dynamic Resource Skill: {skill_name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Universal Skill Generator")
    parser.add_argument("--type", choices=["fixed", "dynamic"], required=True, help="Skill type: fixed (Type 1) or dynamic (Type 2)")
    parser.add_argument("--name", required=True, help="Skill Name (e.g., Silberschatz_DBMS, DBMSSkill)")
    parser.add_argument("--resource-type", default="Book", help="Resource Type (for Type 1: Book, Udemy Course, Manual)")
    parser.add_argument("--source-path", default="", help="Relative source path (e.g., Skills_Input/books/Fundamentals)")
    parser.add_argument("--category-doc", default="dbms categories.docx", help="Category docx/md for Type 2")
    parser.add_argument("--description", default="", help="Brief description of the skill")
    
    args = parser.parse_args()
    if args.type == "fixed":
        create_type1_fixed_resource_skill(args.name, args.resource_type, args.source_path, args.description)
    else:
        create_type2_dynamic_resource_skill(args.name, args.category_doc, args.description)

